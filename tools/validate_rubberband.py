#!/usr/bin/env python3
"""Differential validation of the RUBBER BAND -- retail's player-relative AI
laws -- against the real x86 executed under Unicorn.

Same shape as tools/validate_ai.py: it compiles src/burnout3_ai.c itself into
a probe and diffs THAT against the retail instructions, so what is asserted is
the shipped C, not a paraphrase of it.

Functions under test (analyzed burnout3.elf, .text = flat + 0x10000):

  0x00106370  FUN_00106370  "where am I relative to my human player"
              -> vehicle +0x1554 (which player), +0x1558 (1 me / 2 ahead /
                 3 behind), +0x155C (gap, 0 at 40 m .. 1 at 140 m)
              vs b3_ai_player_rel()

  0x001734C0  FUN_001734C0  THE CATCH-UP
              -> returns the new AI+0x9C4 demand, writes AI+0x9DC (the
                 off-camera warp speed) and latches AI+0xA31 on expiry
              vs b3_ai_catchup()

  0x00173690  FUN_00173690  the hard speed cap
              -> AI+0xA08
              vs b3_ai_speed_cap()

WHY THIS EXISTS
---------------
docs/RE_AI.md 15.6 row 10b recorded FUN_001734C0 as "documented [S], not
ported", and tools/emulate_ai.py's seed_car() pins AI+0xA0C to 1e9 and
AI+0xA31 to 1 with the comment "keep the catch-up branch out unless asked".
Nothing in the suite had ever executed either law, and the port's call site
passed the literal 0.0f for the bonus.  This is the case set that was missing.

TWO STUBS, and why they are honest
----------------------------------
FUN_001734C0 calls FUN_00194380 (the along-track distance of a score object)
and FUN_00106370 calls FUN_00194200 (the lap/checkpoint/distance comparator).
Both walk objects this harness does not build, and both are pure inputs to the
laws under test -- the port takes them as arguments (`race_fraction`,
`ahead_of_player`).  Each is replaced in the emulated image by a 6..9 byte
stub that returns a value this script controls, so the CASE seeds both sides
identically and the diff is over the law, not over the input plumbing.

Run from the repo root:  python3 tools/validate_rubberband.py
"""
import os
import struct
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import emulate_ai as ea                                        # noqa: E402
from unicorn.x86_const import (UC_X86_REG_EAX, UC_X86_REG_EBX,  # noqa: E402
                               UC_X86_REG_ECX, UC_X86_REG_EDX,
                               UC_X86_REG_ESI, UC_X86_REG_EDI)

AI = ea.AI
RC = ea.RC
VEH = ea.VEH
TOL = 1e-5

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "build")
PROBE_C = os.path.join(BUILD, "rb_probe.c")
PROBE = os.path.join(BUILD, "rb_probe")

# The probe links burnout3_backend.c; pin it to the RE path so a flipped
# build/backends.cfg cannot change what this suite measures.
os.environ['B3_BACKENDS'] = '/dev/null'

# --- addresses -------------------------------------------------------------
F_PLAYER_REL = 0x00106370        # -> vehicle +0x1554/+0x1558/+0x155C
F_CATCHUP    = 0x001734C0        # -> AI+0x9C4 return, AI+0x9DC, AI+0xA31
F_SPEED_CAP  = 0x00173690        # -> AI+0xA08
F_TRACK_DIST = 0x00194380        # stubbed: along-track distance
F_OUTRANKS   = 0x00194200        # stubbed: does a outrank b?

G_NCARS_A19C = 0x0073A19C        # count for the DAT_0073A1A8 pointer table
G_CARTAB     = 0x0073A1A8        # the car POINTER table FUN_001734C0 walks
G_NCARS_A1C0 = 0x0073A1C0        # count for the DAT_0073A1D0 object ARRAY
G_CARARRAY   = 0x0073A1D0        # the racecar array, stride 0x27E0
G_SECTIONS   = 0x0073A164        # per-section factor table (0 = none)
G_LAPLEN     = 0x0073A184        # {f32 cumulative length, ...} stride 8
G_LAPLEN_N   = 0x0073A188
G_DIFF_IDX   = 0x0073BB50        # BSS, never written -> place window = 1
G_DIFF_TAB   = 0x003A29EC        # {1,1,2,2,3,3,1}
CAR_STRIDE   = 0x27E0

# scratch for the stubs' return values
STUB_DIST    = 0x0073BC00        # f32 FUN_00194380 returns
STUB_RANK    = 0x0073BC08        # u32 FUN_00194200 returns (in EAX)
OTHER        = ea.OTHER          # 0x70000000, 0x10000 -- the other cars
OTHER_STRIDE = 0x2000            # > 0x1924, the highest offset we touch
LAPTAB       = OTHER + 0x6000    # the {f32 cumulative length, ...} array
PLAYER_VEH   = OTHER + 0x4000    # the paired player's physics vehicle

TOP_SPEED = ea.VDB[ea.P_TOP_SPEED]     # 88.0
MIN_SPEED = ea.VDB[ea.P_MIN_SPEED]     # 20.0

# retail constants, for the report only -- the C reads its own copies
C_RELEASE = 45.0
C_WARP    = 17.8816
C_MARGIN  = 4.4704


