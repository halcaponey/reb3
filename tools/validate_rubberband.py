def install_stubs(s):
    """Replace the two pure-input helpers with constant returns.

    FUN_00194380 -> XMM0 = [STUB_DIST]        (movss xmm0,[imm32]; ret)
    FUN_00194200 -> EAX  = [STUB_RANK]        (mov eax,[imm32]; ret)
    Neither takes stack arguments at the call sites under test, so a plain
    `ret` is the right epilogue for both.
    """
    s.uc.mem_write(F_TRACK_DIST,
                   b"\xF3\x0F\x10\x05" + struct.pack('<I', STUB_DIST) + b"\xC3")
    s.uc.mem_write(F_OUTRANKS,
                   b"\xA1" + struct.pack('<I', STUB_RANK) + b"\xC3")


def new_session():
    s = ea.Session()
    ea.seed_car(s)
    install_stubs(s)
    # no per-section factor table -> FUN_00172BC0 returns "Min speed mps"
    # (@0x00172D05) and FUN_00172D20 returns "Top speed mps" (@0x00172E65)
    s.wu(G_SECTIONS, 0)
    # the difficulty index is BSS and referenced by exactly one instruction in
    # the whole image (the read at 0x001735AC); it is never written.
    s.wu(G_DIFF_IDX, 0)
    for i, v in enumerate((1, 1, 2, 2, 3, 3, 1)):
        s.wi(G_DIFF_TAB + i * 4, v)
    # laps * cumulative length.  DAT_0073A184 is a POINTER to a stride-8
    # record array and DAT_0073A188 the section count; the operand at
    # 0x00173532 is `[edx + eax*8 - 8]`, i.e. the LAST section's cumulative
    # length -- the whole lap.  One section, 1000 m.
    s.wu(G_LAPLEN, LAPTAB)
    s.wu(G_LAPLEN_N, 1)
    s.wf(LAPTAB, 1000.0)
    return s


def seed_cars(s, places, modes):
    """Lay the other cars out in OTHER and publish the pointer table."""
    s.wu(G_NCARS_A19C, len(places))
    for i, (p, m) in enumerate(zip(places, modes)):
        base = OTHER + i * OTHER_STRIDE
        s.uc.mem_write(G_CARTAB + i * 4, struct.pack('<I', base))
        s.uc.mem_write(base + 0x10D0, struct.pack('<h', p))
        s.wi(base + 0x1920, m)


def retail_catchup(case):
    s = new_session()
    seed_cars(s, case["places"], case["modes"])
    s.uc.mem_write(RC + 0x10D0, struct.pack('<h', case["myplace"]))
    s.wi(RC + 0x2450, case["m2450"])
    s.wu(RC + 0x2440, VEH if case["vok"] else 0)
    s.wb(VEH + 0x1550, 1 if case["inrange"] else 0)
    s.wi(VEH + 0x1558, case["rank"])
    s.wf(VEH + 0x155C, case["gapn"])
    # the race fraction: (stub_dist - rc+0x135C) / (rc+0x1394 * 1000)
    if case["distok"]:
        s.wf(RC + 0x135C, 0.0)
        s.wi(RC + 0x1394, 1)
        s.wf(STUB_DIST, case["frac"] * 1000.0)
    else:
        s.wf(RC + 0x135C, -1.0)
        s.wi(RC + 0x1394, 0)
    s.wf(AI + 0x9E8, case["cwin"])
    s.wb(AI + 0xA31, case["expired"])
    s.wf(AI + 0xA04, 123.0)
    s.wf(AI + 0x9DC, -1.0)
    ret = s.call(F_CATCHUP, stack_args=(AI, ea.f2u(case["spd"])))
    return ({"ret": ret,
             "bonus": s.rf(AI + 0x9DC),
             "expired": float(s.rb(AI + 0xA31)),
             "a04": s.rf(AI + 0xA04)}, s.fault)


def retail_cap(case):
    s = new_session()
    s.wu(RC + 0x2440, VEH if case["vok"] else 0)
    s.wb(VEH + 0x1550, 1 if case["inrange"] else 0)
    s.wi(VEH + 0x1558, case["rank"])
    s.wb(VEH + 0x1554, case["pslot"])
    s.wb(AI + 0xA31, case["expired"])
    s.wb(AI + 0xA10, 0xFF)     # no section cursor -> the no-table returns
    # DAT_0073A1D0[pslot] -> +0x2440 -> the player's vehicle, +0xBC its speed
    s.wi(G_NCARS_A1C0, max(1, case["pslot"] + 1))
    pveh = PLAYER_VEH
    s.wu(G_CARARRAY + case["pslot"] * CAR_STRIDE + 0x2440, pveh)
    s.wf(pveh + 0xBC, case["pspeed"])
    s.wf(AI + 0xA08, -1.0)
    s.call(F_SPEED_CAP, stack_args=(AI,))
    return ({"cap": s.rf(AI + 0xA08)}, s.fault)


def retail_rel(case):
    s = new_session()
    s.wi(RC + 0x1920, case["rmode"])
    s.wi(G_NCARS_A1C0, case["nc"])
    s.wb(RC + 0x19BC, case["grid"])
    s.wb(RC + 0x27D0, case["grid"])
    s.wu(STUB_RANK, 1 if case["ahead"] else 0)
    # vehicle+0x1560[k]: FUN_00105BD0's squared-distance cache
    for k in range(4):
        s.wf(VEH + 0x1560 + k * 4, case["d2"])
    s.wb(VEH + 0x1554, 0x7F)
    s.wi(VEH + 0x1558, -1)
    s.wf(VEH + 0x155C, -1.0)
    s.call(F_PLAYER_REL, regs={UC_X86_REG_ESI: VEH})
    ps = s.rb(VEH + 0x1554)
    if ps >= 0x80:
        ps -= 0x100
    return ({"pslot": float(ps),
             "rank": float(s.ri(VEH + 0x1558)),
             "gap": s.rf(VEH + 0x155C)}, s.fault)


