def close(a, b):
    if a == b:
        return True
    d = abs(a - b)
    return d <= TOL or d <= TOL * max(abs(a), abs(b))


def main():
    ai_src = os.path.join(ROOT, "src", "burnout3_ai.c")
    for i, a in enumerate(sys.argv):
        if a == "--ai-src" and i + 1 < len(sys.argv):
            ai_src = os.path.abspath(sys.argv[i + 1])
    build_probe(ai_src)

    groups = (("FUN_00106370  player-relative block", REL_CASES, retail_rel,
               "rel", ("pslot", "rank", "gap")),
              ("FUN_001734C0  the catch-up", CATCHUP_CASES, retail_catchup,
               "catchup", ("ret", "bonus", "expired", "a04")),
              ("FUN_00173690  the hard speed cap", CAP_CASES, retail_cap,
               "cap", ("cap",)))

    npass = nfail = 0
    for title, cases, runner, op, fields in groups:
        print("\n=== %s ===" % title)
        for c in cases:
            want, fault = runner(c)
            if fault:
                print("  FAULT %-44s %s" % (c["name"], fault))
                nfail += 1
                continue
            seeds = {k: v for k, v in c.items()
                     if k not in ("name", "places", "modes")}
            if op == "catchup":
                for i, p in enumerate(c["places"]):
                    seeds["place%d" % i] = p
                for i, m in enumerate(c["modes"]):
                    seeds["mode%d" % i] = m
                seeds["ncars"] = len(c["places"])
            got = run_probe(op, seeds)
            bad = [f for f in fields if not close(got.get(f, 1e30), want[f])]
            if bad:
                nfail += 1
                print("  FAIL  %-44s %s" % (c["name"],
                      " ".join("%s retail=%.6g port=%.6g"
                               % (f, want[f], got.get(f, float('nan')))
                               for f in bad)))
            else:
                npass += 1
                print("  ok    %-44s %s" % (c["name"],
                      " ".join("%s=%.6g" % (f, want[f]) for f in fields)))

    print("\n%d/%d cases match retail" % (npass, npass + nfail))

    # ---- the behavioural assertion the report is about --------------------
    print("\n=== the catch-up RESPONSE to the player's lead ===")
    print("  a rival one place behind the player, window open:")
    base = catchup_case("probe")
    prev = None
    ok = True
    for gap_m in (0.0, 40.0, 60.0, 80.0, 100.0, 120.0, 140.0, 200.0):
        rel = retail_rel(rel_case("g", d2=gap_m * gap_m))[0]
        c = dict(base, gapn=rel["gap"])
        want, _ = retail_catchup(c)
        seeds = {k: v for k, v in c.items()
                 if k not in ("name", "places", "modes")}
        for i, p in enumerate(c["places"]):
            seeds["place%d" % i] = p
        for i, m in enumerate(c["modes"]):
            seeds["mode%d" % i] = m
        seeds["ncars"] = len(c["places"])
        got = run_probe("catchup", seeds)
        agree = close(got["bonus"], want["bonus"]) and close(got["ret"],
                                                             want["ret"])
        ok &= agree
        print("    %5.0f m  warp %6.3f m/s (%5.1f mph)  demand %5.1f -> %5.1f"
              "   %s" % (gap_m, want["bonus"], want["bonus"] * 2.2369363,
                         c["spd"], want["ret"],
                         "match" if agree else "MISMATCH"))
        if prev is not None and want["bonus"] < prev - TOL:
            ok = False
            print("      NOT MONOTONIC in the gap")
        prev = want["bonus"]
    if prev is None or prev <= 0.0:
        ok = False
    print("  monotonic non-decreasing in the gap, both backends: %s"
          % ("yes" if ok else "NO"))
    if not ok:
        nfail += 1

    print("\n=== the speed cap's RESPONSE to the player's speed ===")
    print("  a rival whose catch-up has expired:")
    prev = None
    ok2 = True
    for ps in (0.0, 10.0, 20.0, 30.0, 45.0, 60.0, 80.0):
        c = cap_case("g", expired=1, pspeed=ps)
        want, _ = retail_cap(c)
        seeds = {k: v for k, v in c.items() if k != "name"}
        got = run_probe("cap", seeds)
        agree = close(got["cap"], want["cap"])
        ok2 &= agree
        print("    player %5.1f m/s -> rival ceiling %5.1f m/s   %s"
              % (ps, want["cap"], "match" if agree else "MISMATCH"))
        if prev is not None and want["cap"] < prev - TOL:
            ok2 = False
        prev = want["cap"]
    print("  ceiling tracks the player's speed on both backends: %s"
          % ("yes" if ok2 else "NO"))
    if not ok2:
        nfail += 1

    if nfail:
        print("\n%d FAILURES" % nfail)
        return 1
    print("\nALL GREEN")
    return 0


