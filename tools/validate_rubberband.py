def build_probe(ai_src):
    os.makedirs(BUILD, exist_ok=True)
    with open(PROBE_C, "w") as f:
        f.write(PROBE_SRC % {"AI_SRC": ai_src,
                             "TOP_SPEED": TOP_SPEED,
                             "MIN_SPEED": MIN_SPEED})
    cmd = ["gcc", "-std=c11", "-O1", "-I", os.path.join(ROOT, "src"),
           "-I", os.path.dirname(ai_src),
           "-Wno-address-of-packed-member",
           PROBE_C,
           os.path.join(ROOT, "src", "burnout3_backend.c"),
           os.path.join(ROOT, "src", "burnout3_emu.c"),
           "-lm", "-o", PROBE]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit("probe build failed:\n" + r.stdout + r.stderr)


def run_probe(op, seeds):
    args = [PROBE, op] + ["%s=%s" % (k, v) for k, v in sorted(seeds.items())]
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode:
        sys.exit("probe failed (%s): %s%s" % (op, r.stdout, r.stderr))
    out = {}
    for tok in r.stdout.split():
        k, _, v = tok.partition('=')
        out[k] = float(v)
    return out


